/**
 * The React spelling of an HTML attribute name: `tabindex` is `tabIndex`,
 * `for` is `htmlFor`; a name React spells as HTML does passes unchanged.
 *
 * @param name - The attribute name in its HTML spelling.
 * @returns The React prop name.
 */
export function attributeName(name: string): string {
  return REACT_ATTRIBUTE_NAMES[name] ?? name;
}
